/**
 * The Python judge, off the main thread.
 *
 * A plain script in public/ rather than a bundled module: Turbopack's worker
 * runtime loads its chunks with importScripts, which a module worker forbids,
 * so anything it compiles into a worker dies with "classic web workers are not
 * supported". This file is never processed by the bundler at all.
 *
 * A worker rather than the page for one reason: an infinite loop. Pyodide's
 * own interrupt mechanism needs a SharedArrayBuffer, which needs cross-origin
 * isolation headers that would break embeds elsewhere on the site — whereas a
 * worker can simply be terminated. The page starts a timer, and if the timer
 * wins it kills this thread outright. That costs a fresh boot on the next run
 * and works against any loop a student can write.
 *
 * Comparison of answers is deliberately NOT done here. It happens on the page,
 * against expectations generated by running reference solutions, so the rule
 * that decides right from wrong is not something student code shares a
 * process with.
 */

/*
 * Absolute, and handed in by the page. A blob worker has no origin-relative
 * base, so "/pyodide/pyodide.js" is not a URL it can resolve.
 */
importScripts(self.__PYODIDE_BASE__ + "pyodide.js");

let ready = null;

function boot() {
  ready ??= loadPyodide({ indexURL: self.__PYODIDE_BASE__ });
  return ready;
}

/**
 * Runs the student's code against every case and reports what came back.
 *
 * Values are made JSON-safe first: a student may legitimately return a tuple
 * or a set, and `json.dumps` would raise on both — reporting a crash for a
 * correct answer. Everything unrecognised falls back to its repr so the page
 * can still show the student what they returned.
 */
const HARNESS = `
import copy, json, traceback

def _jsonable(value):
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, (list, tuple)):
        return [_jsonable(v) for v in value]
    if isinstance(value, set):
        return sorted((_jsonable(v) for v in value), key=repr)
    if isinstance(value, dict):
        return {str(k): _jsonable(v) for k, v in value.items()}
    return repr(value)

def _judge(source, entry, cases, compare):
    namespace = {}
    try:
        exec(source, namespace)
    except Exception:
        return json.dumps({"fatal": traceback.format_exc(limit=3).strip()})

    if "Solution" not in namespace:
        return json.dumps({"fatal": "No class named Solution was defined."})

    results = []
    for case in cases:
        args = copy.deepcopy(case["args"])
        try:
            method = getattr(namespace["Solution"](), entry, None)
            if method is None:
                return json.dumps(
                    {"fatal": "Solution has no method called " + entry + "."}
                )
            returned = method(*args)

            kind = compare["kind"]
            if kind == "inplace":
                got = args[compare["arg"]]
            elif kind == "k_prefix":
                mutated = args[compare["arg"]]
                got = (
                    {"k": returned, "prefix": mutated[:returned]}
                    if isinstance(returned, int)
                    else {"k": returned, "prefix": None}
                )
            else:
                got = returned

            results.append({"got": _jsonable(got)})
        except Exception:
            line = traceback.format_exc(limit=1).strip().split("\\n")[-1]
            results.append({"error": line})

    return json.dumps({"results": results})
`;

self.onmessage = async (event) => {
  const { id, source, entry, cases, compare, warmup } = event.data;

  /*
   * A warm-up message carries no work: the page sends one on mount so the
   * 13 MB runtime downloads while the student is still reading the problem,
   * and so the run timer measures their code rather than our download.
   */
  if (warmup) {
    try {
      await boot();
      self.postMessage({ ready: true });
    } catch (error) {
      self.postMessage({ ready: false, error: String(error) });
    }
    return;
  }

  try {
    const pyodide = await boot();
    pyodide.runPython(HARNESS);

    // Student output goes nowhere: a print() in a loop must not be able to
    // flood the page, and nothing here reads stdout.
    pyodide.setStdout({ batched: () => {} });
    pyodide.setStderr({ batched: () => {} });

    const judge = pyodide.globals.get("_judge");
    const raw = judge(source, entry, pyodide.toPy(cases), pyodide.toPy(compare));
    judge.destroy();

    self.postMessage({ id, ok: true, payload: JSON.parse(raw) });
  } catch (error) {
    self.postMessage({ id, ok: false, error: String(error) });
  }
};
