/**
 * The price book: what the services we build on cost, as a set of
 * spreadsheet-style tables. Generated from the team's research workbook
 * (AI_Infra_Pricing_Research.xlsx, prices checked on CHECKED), so a number
 * here is the workbook's number. Columns the workbook worked out in rupees
 * from dollars are left out: each money cell keeps the currency it was
 * quoted in, and the page converts at FX_INR_PER_USD.
 *
 * Confidence is the workbook's: "Official" is the vendor's own pricing
 * page, "Secondary" a third-party source, "Low" inferred or conflicting.
 */

import { TEAM_RATES_CHECKED, TEAM_ROLES } from "@/lib/team-rates";

export type Money = { usd: number } | { inr: number };
const usd = (amount: number): Money => ({ usd: amount });
const inr = (amount: number): Money => ({ inr: amount });

/** One cell. A string in a money or number column is a word like "Custom". */
export type Cell = string | number | Money | null;

export type Column = {
  label: string;
  /**
   * text: short words; long: a sentence or more (wraps wide); money: a
   * price; number: a count or size (with `unit`); percent: a fraction
   * shown as %; confidence: Official / Secondary / Low; link: an https
   * address, shown as its site's name; points: a short list, one point
   * per line.
   */
  kind:
    | "text"
    | "long"
    | "points"
    | "money"
    | "number"
    | "percent"
    | "confidence"
    | "link";
  unit?: string;
  /** Offer a filter of this column's values above the table. */
  facet?: boolean;
};

export type PriceRow = {
  /** Stable across edits: "w3" for the workbook's fourth row, a uuid for added ones. */
  id: string;
  /** In column order. */
  cells: Cell[];
  /** Where the row's name links to (our provider pages). */
  href?: string;
};

export type PriceTable = {
  id: string;
  title: string;
  note?: string;
  /** Whether rows can be ticked and set side by side. */
  compare: boolean;
  /** The columns that together name a row (for the comparison's headings). */
  nameColumns: number[];
  /**
   * Show one block per value of this column (a company), its rows (plans)
   * stacked beside it, rather than repeating the company on every row.
   */
  groupBy?: number;
  /** Questions and answers shown under the table, and where they are from. */
  faq?: { q: string; a: string }[];
  faqSource?: { label: string; url: string };
  columns: Column[];
  rows: PriceRow[];
  /** Set when the team has changed this table from the workbook. */
  edited?: { at: string; by: string };
};

export type Sheet = {
  slug: string;
  title: string;
  lede: string;
  tables: PriceTable[];
  /** Prices the workbook says to confirm before relying on them. */
  checks: string[];
  sources: { label: string; url: string }[];
};

/** A sheet as generated from the workbook, rows still as plain cell lists. */
type WorkbookSheet = Omit<Sheet, "tables"> & {
  tables: (Omit<PriceTable, "rows"> & { rows: Cell[][] })[];
};

