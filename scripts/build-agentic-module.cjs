/** Dollar-quotes a body with a tag the body cannot contain. */
function quote(body) {
  let tag = "notes_md";
  while (body.includes(`$${tag}$`)) tag += "_x";
  return `$${tag}$${body}$${tag}$`;
}

const parts = [
  `-- 0008 — the Agentic AI module.
--
-- Generated by scripts/build-agentic-module.cjs from content/agentic-ai/.
-- Edit the markdown there and re-run the script; do not edit this file.
--
-- Idempotent: lessons upsert against the (module_id, day_label) unique index
-- added in 0008a, so re-running updates the text rather than adding a copy.

insert into public.modules (slug, title, summary, position)
values (
  'agentic-ai',
  'Agentic AI & Applied ML',
  'Enough data science to be useful, then agents in depth: retrieval, MCP, memory and what it takes to ship one.',
  3
)
on conflict (slug) do update
  set title = excluded.title,
      summary = excluded.summary,
      position = excluded.position;
`,
];

for (const [index, lesson] of LESSONS.entries()) {
  const body = fs.readFileSync(path.join(DIR, lesson.file), "utf8").trimEnd();

  // One upsert per lesson, against the (module_id, day_label) unique index —
  // so the body appears once rather than in a paired insert and update.
  parts.push(`
-- ${lesson.day} — ${lesson.title}
insert into public.lessons
  (module_id, day_label, title, summary, body_md, position, is_published)
select m.id,
       ${quote(lesson.day)},
       ${quote(lesson.title)},
       ${quote(lesson.summary)},
       ${quote(body)},
       ${index + 1},
       true
from public.modules m
where m.slug = 'agentic-ai'
on conflict (module_id, day_label) do update
  set title = excluded.title,
      summary = excluded.summary,
      body_md = excluded.body_md,
      position = excluded.position,
      is_published = true,
      updated_at = now();
`);
}

fs.writeFileSync(OUT, parts.join("\n"));

const bytes = fs.statSync(OUT).size;
console.log(
  `Wrote ${path.relative(process.cwd(), OUT)} — ${LESSONS.length} lessons, ${Math.round(bytes / 1024)} KB.`,
);
