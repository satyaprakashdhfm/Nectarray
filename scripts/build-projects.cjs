#!/usr/bin/env node
/**
 * Generates the project seed migration from content/projects/.
 *
 * Same arrangement as the lessons: the briefs live as markdown so they can be
 * read and diffed like anything else, and this turns them into one idempotent
 * migration keyed on the project slug.
 */

const fs = require("node:fs");
const path = require("node:path");

const DIR = path.join(__dirname, "..", "content", "projects");
const OUT = path.join(
  __dirname,
  "..",
  "supabase",
  "migrations",
  "0009a_projects_seed.sql",
);

const PROJECTS = [
  {
    file: "1-data-clean",
    slug: "data-clean",
    title: "A messy file, cleaned",
    summary:
      "Take a real, dirty dataset and produce a clean one — plus a defence of every decision you made.",
  },
  {
    file: "2-model-train",
    slug: "model-train",
    title: "A model you can defend",
    summary:
      "Train a small model properly: an honest split, everything inside a pipeline, and a metric you chose before you saw the score.",
  },
  {
    file: "3-rag-pipeline",
    slug: "rag-pipeline",
    title: "A RAG pipeline with a number",
    summary:
      "Retrieval over documents you choose, with a measured recall figure rather than a demo that looks convincing.",
  },
  {
    file: "4-mcp-agent",
    slug: "mcp-agent",
    title: "An MCP server and an agent that uses it",
    summary:
      "Expose a real system as MCP tools, then drive it from an agent — including one tool that refuses.",
  },
  {
    file: "5-capstone",
    slug: "capstone",
    title: "The whole thing",
    summary:
      "One system: retrieval, an MCP server, an agent, memory across sessions, and an evaluation set that proves it.",
  },
];

/** Dollar-quotes a body with a tag the body cannot contain. */
function quote(body) {
  let tag = "md";
  while (body.includes(`$${tag}$`)) tag += "_x";
  return `$${tag}$${body}$${tag}$`;
}

const read = (name) =>
  fs.readFileSync(path.join(DIR, `${name}.md`), "utf8").trimEnd();

const parts = [
  `-- 0009a — the five project briefs.
--
-- Generated by scripts/build-projects.cjs from content/projects/.
-- Edit the markdown there and re-run the script; do not edit this file.
`,
];

for (const [index, project] of PROJECTS.entries()) {
  parts.push(`
insert into public.projects
  (module_id, position, slug, title, summary, brief_md, rubric_md)
select m.id,
       ${index + 1},
       ${quote(project.slug)},
       ${quote(project.title)},
       ${quote(project.summary)},
       ${quote(read(project.file))},
       ${quote(read(`${project.file}.rubric`))}
from public.modules m
where m.slug = 'agentic-ai'
on conflict (slug) do update
  set title = excluded.title,
      summary = excluded.summary,
      brief_md = excluded.brief_md,
      rubric_md = excluded.rubric_md,
      position = excluded.position;
`);
}

fs.writeFileSync(OUT, parts.join("\n"));
console.log(
  `Wrote ${path.relative(process.cwd(), OUT)} — ${PROJECTS.length} projects.`,
);
